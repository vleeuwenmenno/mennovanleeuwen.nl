// How many columns a character takes in a terminal: 0 for combining marks and other zero-width
// characters, 2 for East Asian wide and full-width characters and emoji, 1 for the rest. It
// follows wcwidth as glibc and tmux have it closely enough for the programs a terminal runs; an
// emulator and the program have to agree, or the cursor drifts.

const ZERO = /^[\p{Mn}\p{Me}\p{Cf}]$/u
const EMOJI = /^\p{Emoji_Presentation}$/u

// East Asian Wide and Fullwidth ranges (Unicode 15), as start/end pairs.
const WIDE = [
  0x1100, 0x115f, 0x231a, 0x231b, 0x2329, 0x232a, 0x23e9, 0x23ec, 0x23f0, 0x23f0, 0x23f3, 0x23f3, 0x25fd, 0x25fe, 0x2614, 0x2615, 0x2648, 0x2653, 0x267f, 0x267f, 0x2693, 0x2693, 0x26a1, 0x26a1,
  0x26aa, 0x26ab, 0x26bd, 0x26be, 0x26c4, 0x26c5, 0x26ce, 0x26ce, 0x26d4, 0x26d4, 0x26ea, 0x26ea, 0x26f2, 0x26f3, 0x26f5, 0x26f5, 0x26fa, 0x26fa, 0x26fd, 0x26fd, 0x2705, 0x2705, 0x270a, 0x270b,
  0x2728, 0x2728, 0x274c, 0x274c, 0x274e, 0x274e, 0x2753, 0x2755, 0x2757, 0x2757, 0x2795, 0x2797, 0x27b0, 0x27b0, 0x27bf, 0x27bf, 0x2b1b, 0x2b1c, 0x2b50, 0x2b50, 0x2b55, 0x2b55, 0x2e80, 0x303e,
  0x3041, 0x33ff, 0x3400, 0x4dbf, 0x4e00, 0x9fff, 0xa000, 0xa4cf, 0xa960, 0xa97f, 0xac00, 0xd7a3, 0xf900, 0xfaff, 0xfe10, 0xfe19, 0xfe30, 0xfe6f, 0xff00, 0xff60, 0xffe0, 0xffe6, 0x16fe0, 0x16fe4,
  0x17000, 0x18aff, 0x1b000, 0x1b2ff, 0x1f004, 0x1f004, 0x1f0cf, 0x1f0cf, 0x1f18e, 0x1f18e, 0x1f191, 0x1f19a, 0x1f200, 0x1f251, 0x1f300, 0x1f64f, 0x1f680, 0x1f6ff, 0x1f7e0, 0x1f7eb, 0x1f90c, 0x1f9ff,
  0x1fa70, 0x1faff, 0x20000, 0x2fffd, 0x30000, 0x3fffd,
]

const cache = new Map<number, number>()

export function charWidth(cp: number): number {
  if (cp < 0x300) return cp < 0x20 || (cp >= 0x7f && cp < 0xa0) ? 0 : 1
  const known = cache.get(cp)
  if (known !== undefined) return known
  let w = 1
  const ch = String.fromCodePoint(cp)
  if (ZERO.test(ch) || (cp >= 0x1160 && cp <= 0x11ff)) w = 0
  else if (EMOJI.test(ch)) w = 2
  else {
    for (let i = 0; i < WIDE.length; i += 2) {
      if (cp < WIDE[i]) break
      if (cp <= WIDE[i + 1]) {
        w = 2
        break
      }
    }
  }
  cache.set(cp, w)
  return w
}
