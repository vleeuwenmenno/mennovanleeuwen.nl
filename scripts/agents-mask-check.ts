// Synthetic mask integration checks against an isolated Vite server; no API, account or GPU.
// DATA_DIR=<scratch> ./node_modules/.bin/vite --port 5283 --strictPort
// node scripts/agents-mask-check.ts http://127.0.0.1:5283
import assert from 'node:assert/strict'
import { launch, newPage } from './perf/cdp.ts'
import { decodePng } from './perf/png.ts'

const url = process.argv[2]
if (!url) throw new Error('Pass the URL of your scratch Vite server.')
const browser = await launch(1100, 900)
try {
  const page = await newPage(browser, 1100, 900, '')
  await page.send('Page.navigate', { url: `${url}/scripts/fixtures/agents-mask.html` })
  const ready = () => page.waitFor(`document.querySelector('canvas')?.getAttribute('aria-disabled') === 'false'`)
  const button = (text: string) => page.eval(`Array.from(document.querySelectorAll('button')).find(b => b.textContent === ${JSON.stringify(text)}).click()`)
  const key = async (key: string, code: string, modifiers = 0) => {
    await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key, code, modifiers, windowsVirtualKeyCode: key === 'Escape' ? 27 : key === 'Tab' ? 9 : 0 })
    await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key, code, modifiers, windowsVirtualKeyCode: key === 'Escape' ? 27 : key === 'Tab' ? 9 : 0 })
  }
  const mount = async (options = '{}') => { await page.eval(`window.mountMask(${options})`); await ready() }
  const at = (x: number, y: number) => page.eval<{ x: number; y: number }>(`(() => { const r = document.querySelector('canvas').getBoundingClientRect(); return { x:r.x+r.width*${x}, y:r.y+r.height*${y} } })()`)
  const apply = async () => {
    await page.eval('window.maskResult = undefined')
    await button('Apply mask')
    await page.waitFor('!!window.maskResult')
    const result = await page.eval<{ bytes: number[]; width: number; height: number }>('window.maskResult')
    const bytes = Buffer.from(result.bytes)
    assert.ok([2, 6].includes(bytes[25]), 'PNG uses RGB or opaque RGBA')
    const png = decodePng(bytes)
    assert.equal(png.width, 640)
    assert.equal(png.height, 400)
    assert.equal(result.width, 640)
    assert.equal(result.height, 400)
    assert.ok(bytes.length <= 8 * 1024 * 1024)
    for (let i = 0; i < png.data.length; i += 4) {
      assert.ok(png.data[i] === 0 || png.data[i] === 255)
      assert.equal(png.data[i], png.data[i + 1])
      assert.equal(png.data[i], png.data[i + 2])
      assert.equal(png.data[i + 3], 255)
    }
    return (x: number, y: number) => png.data[(y * png.width + x) * 4]
  }
  await ready()
  assert.deepEqual(await page.eval(`(async () => {
    const { maskDimensionsValid: valid } = await import('/src/apps/AgentsMaskEditor.tsx')
    return [valid(4096, 4096), valid(8192, 2048), valid(4096, 4097), valid(8193, 1)]
  })()`), [true, true, false, false])
  console.log('PASS 4096-square / 16,777,216-pixel and 8192-side boundaries')
  assert.equal(await page.eval('document.activeElement.textContent'), 'Cancel')
  assert.equal(await page.eval(`document.querySelector('.agt-mask-apply').disabled`), true)
  let p = await at(.25, .25)
  await page.click(p.x, p.y)
  let pixel = await apply()
  assert.equal(pixel(160, 100), 255)
  assert.equal(pixel(320, 200), 0)
  await button('Erase')
  await page.click(p.x, p.y)
  await button('Apply mask')
  await page.waitFor(`document.querySelector('[role=alert]')?.textContent.includes('empty')`)
  await button('Undo')
  pixel = await apply()
  assert.equal(pixel(160, 100), 255)
  await button('Reset')
  assert.equal(await page.eval(`document.querySelector('.agt-mask-apply').disabled`), true)
  console.log('PASS RGB binary export, source coordinates, erase/empty, undo, reset')

  await button('Brush')
  await page.eval(`document.querySelector('canvas').focus()`)
  await key('ArrowRight', 'ArrowRight')
  await key(' ', 'Space')
  pixel = await apply()
  assert.equal(pixel(168, 100), 255)
  await page.eval(`document.querySelector('canvas').focus()`)
  await key('z', 'KeyZ', 2)
  assert.equal(await page.eval(`document.querySelector('.agt-mask-apply').disabled`), true)
  await key('Tab', 'Tab', 1)
  assert.ok(await page.eval(`document.querySelector('dialog').contains(document.activeElement)`))
  console.log('PASS keyboard drawing, undo shortcut and modal focus containment')

  await page.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  await page.send('Emulation.setTouchEmulationEnabled', { enabled: true })
  await mount()
  assert.ok(await page.eval(`document.querySelector('dialog').scrollWidth <= document.querySelector('dialog').clientWidth`))
  p = await at(.75, .75)
  await page.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: p.x, y: p.y }] })
  await page.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  pixel = await apply()
  assert.equal(pixel(480, 300), 255)
  await page.send('Emulation.setDeviceMetricsOverride', { width: 1000, height: 800, deviceScaleFactor: 1, mobile: false })
  p = await at(.25, .25)
  await page.click(p.x, p.y)
  pixel = await apply()
  assert.equal(pixel(480, 300), 255)
  assert.equal(pixel(160, 100), 255)
  await button('Reset')
  p = await at(.5, .5)
  await page.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: p.x, y: p.y }] })
  await page.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  assert.equal(await page.eval(`document.querySelector('.agt-mask-apply').disabled`), true)
  console.log('PASS phone fit, touch, resize alignment and canceled pointer rollback')

  await page.eval(`window.penCaptured = false; document.querySelector('canvas').addEventListener('gotpointercapture', () => window.penCaptured = true, { once:true })`)
  await page.send('Input.dispatchMouseEvent', { type: 'mousePressed', x: p.x, y: p.y, button: 'left', buttons: 1, clickCount: 1, pointerType: 'pen' })
  await page.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: p.x + 20, y: p.y, button: 'left', buttons: 1, pointerType: 'pen' })
  await page.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 999, y: p.y, button: 'left', buttons: 1, pointerType: 'pen' })
  await page.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 999, y: p.y, button: 'left', buttons: 0, clickCount: 1, pointerType: 'pen' })
  assert.equal(await page.eval('window.penCaptured'), true)
  pixel = await apply()
  assert.equal(pixel(639, 200), 255)
  await button('Reset')
  console.log('PASS pen drawing and pointer capture outside canvas')

  // Abort while toBlob is pending: cancel must suppress the callback.
  await page.click(p.x, p.y)
  await page.eval(`window.originalToBlob = HTMLCanvasElement.prototype.toBlob; HTMLCanvasElement.prototype.toBlob = function(cb, type) { window.pendingMask = () => window.originalToBlob.call(this, cb, type) }`)
  await button('Apply mask')
  await button('Cancel')
  await page.eval(`window.maskResult = undefined; window.pendingMask(); HTMLCanvasElement.prototype.toBlob = window.originalToBlob`)
  await page.eval('new Promise(r => setTimeout(r, 100))')
  assert.equal(await page.eval('window.maskResult === undefined && window.maskCanceled'), true)
  await mount()
  await page.eval(`document.querySelector('canvas').focus()`)
  await key(' ', 'Space')
  await page.eval(`HTMLCanvasElement.prototype.toBlob = function(cb) { cb(new Blob([new Uint8Array(8 * 1024 * 1024 + 1)], { type: 'image/png' })) }`)
  await button('Apply mask')
  await page.waitFor(`document.querySelector('[role=alert]')?.textContent.includes('exceeds 8 MiB')`)
  await page.eval('HTMLCanvasElement.prototype.toBlob = window.originalToBlob')
  console.log('PASS cancel during export and oversized PNG error')

  for (const options of ['{width:8193}', '{width:8192,height:8192}', '{width:0}', '{width:1.5}', '{sourceUrl:"https://example.invalid/image.png"}']) {
    await page.eval(`window.mountMask(${options})`)
    await page.waitFor(`!!document.querySelector('[role=alert]')`)
    assert.equal(await page.eval(`document.querySelector('img') === null`), true)
  }
  await page.eval('window.mountMask({width:400,height:640})')
  await page.waitFor(`document.querySelector('[role=alert]')?.textContent.includes('dimensions do not match')`)
  await mount()
  await page.eval(`document.querySelector('canvas').focus()`)
  await page.eval(`(async () => { for (let i=0;i<513;i++) { document.querySelector('canvas').dispatchEvent(new KeyboardEvent('keydown', { key:' ', bubbles:true })); if (i%32===0) await new Promise(r=>setTimeout(r,0)) } })()`)
  await page.waitFor(`document.querySelector('[role=alert]')?.textContent.includes('history is full')`)
  await button('Undo')
  assert.equal(await page.eval(`document.querySelector('[role=alert]') === null`), true)
  await key('Escape', 'Escape')
  await page.waitFor('window.maskCanceled')
  await page.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
  async function beginInpaint(attachment = false) {
    await page.eval(`window.mountInpaint(${attachment})`)
    await page.waitFor(`!!document.querySelector('textarea')`)
    assert.ok(await page.eval(`document.querySelector('.image-dialog').getBoundingClientRect().right <= innerWidth`))
    await page.clickText('textarea')
    await page.send('Input.insertText', { text: 'Replace the marked sky' })
    await page.waitFor(`Array.from(document.querySelectorAll('button')).some(b=>b.textContent==='Paint edit area'&&!b.disabled)`)
    await button('Paint edit area')
    await ready()
    await page.eval(`document.querySelector('canvas').focus()`)
    await key(' ', 'Space')
  }
  await beginInpaint()
  await button('Cancel')
  assert.equal(await page.eval('window.maskUploads'),0)
  await beginInpaint()
  await button('Apply mask')
  await page.waitFor('!!window.inpaintResult')
  assert.deepEqual(await page.eval('window.inpaintResult'), { operation:'inpaint', source_image_id:'00000000-0000-4000-8000-000000000002', mask_id:'00000000-0000-4000-8000-000000000001', prompt:'Replace the marked sky', denoise:0.65 })
  assert.equal(await page.eval('window.maskUploads'),1)
  await beginInpaint()
  await page.eval('window.holdMaskUpload=true')
  await button('Apply mask')
  await page.waitFor('!!window.finishMaskUpload')
  await button('Cancel')
  await page.eval('window.finishMaskUpload()')
  await page.waitFor('window.maskDiscards===1')
  assert.equal(await page.eval('window.inpaintResult===undefined'),true)
  await beginInpaint(true)
  await button('Apply mask')
  await page.waitFor('!!window.inpaintResult')
  assert.deepEqual(await page.eval('window.inpaintResult'), { operation:'inpaint', source_image_id:'attachment:42:0', mask_id:'00000000-0000-4000-8000-000000000001', prompt:'Replace the marked sky', denoise:0.65 })
  assert.equal(await page.eval('window.maskUploads'),1)
  await page.eval(`window.mountMask({sourceUrl:'/scripts/fixtures/agent-image-sources/rotated.jpg',width:32,height:48})`)
  await ready()
  await page.eval(`document.querySelector('canvas').focus()`)
  await key(' ', 'Space')
  await button('Apply mask')
  await page.waitFor('!!window.maskResult')
  const oriented = await page.eval<{bytes:number[];width:number;height:number}>('window.maskResult')
  assert.deepEqual([oriented.width,oriented.height],[32,48])
  const orientedPng = decodePng(Buffer.from(oriented.bytes))
  assert.deepEqual([orientedPng.width,orientedPng.height],[32,48])
  assert.equal(orientedPng.data[(24*32+16)*4],255)
  console.log('PASS browser EXIF-oriented JPEG and exported mask share portrait coordinates')
  console.log('PASS attachment source: decoded dimensions, owned reference, no fabricated diffusion settings')
  console.log('PASS prompt-to-editor-to-inpaint wiring, no upload on cancel, late upload discarded without generation')
  assert.deepEqual(page.errors, [])
  console.log('PASS dimensions/origin validation, bounded history, Escape and no browser errors')
} finally {
  await browser.close()
}
